const fs = require('node:fs')
const path = require('node:path')

const repositoryRoot = path.resolve(__dirname, '..')
const sourceRoot = path.join(repositoryRoot, 'src')
const outputPath = path.join(repositoryRoot, 'example', 'fixtures', 'catalog.ts')

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name)
    if (entry.isDirectory()) return walk(entryPath)
    return entry.isFile() && entry.name.endsWith('.tsx') ? [entryPath] : []
  })
}

function readTag(source, tag) {
  const match = source.match(new RegExp(`@${tag}\\s+([^\\r\\n*]+)`))
  return match?.[1].trim() || null
}

function fallbackName(filePath) {
  return path
    .basename(filePath, path.extname(filePath))
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (character) => character.toUpperCase())
}

function toPosix(value) {
  return value.split(path.sep).join('/')
}

function stringLiteral(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function displayWidth(value) {
  return [...value].reduce(
    (width, character) =>
      width +
      (/^[\u1100-\u115f\u2329\u232a\u2e80-\u303e\u3040-\ua4cf\uac00-\ud7a3\uf900-\ufaff\ufe10-\ufe6f\uff00-\uff60\uffe0-\uffe6]$/u.test(
        character,
      )
        ? 2
        : 1),
    0,
  )
}

function propertyLine(name, value) {
  const line = `    ${name}: ${stringLiteral(value)},`
  return displayWidth(line) > 100 ? `    ${name}:\n      ${stringLiteral(value)},` : line
}

const fixtureFiles = walk(sourceRoot)
  .filter((filePath) => filePath.split(path.sep).includes('__fixtures__'))
  .sort((left, right) => left.localeCompare(right))

const fixtures = fixtureFiles.map((filePath, index) => {
  const source = fs.readFileSync(filePath, 'utf8')
  const relativeSourcePath = toPosix(path.relative(repositoryRoot, filePath))
  const sourceParts = relativeSourcePath.split('/')
  const fixtureIndex = sourceParts.indexOf('__fixtures__')
  const component = sourceParts.slice(1, fixtureIndex).join('/')
  const fixturePath = sourceParts
    .slice(fixtureIndex + 1)
    .join('/')
    .replace(/\.tsx$/, '')
  const fallback = fallbackName(filePath)
  const title = readTag(source, 'title') || fallback
  const description = readTag(source, 'description') || fallback

  return {
    component,
    description,
    id: `${component}/${fixturePath}`,
    importName: `Fixture${index}`,
    importPath: `../../${relativeSourcePath.replace(/\.tsx$/, '')}`,
    title,
  }
})

const imports = fixtures
  .map(({ importName, importPath }) => `import ${importName} from '${importPath}'`)
  .join('\n')
const entries = fixtures
  .map(({ component, description, id, importName, title }) =>
    [
      '  {',
      `    Component: ${importName},`,
      propertyLine('component', component),
      propertyLine('description', description),
      propertyLine('id', id),
      propertyLine('title', title),
      '  },',
    ].join('\n'),
  )
  .join('\n')

const output = `// This file is generated by scripts/generate-fixture-catalog.cjs.\nimport type { ComponentType } from 'react'\n\n${imports}\n\nexport interface FixtureEntry {\n  Component: ComponentType\n  component: string\n  description: string\n  id: string\n  title: string\n}\n\nexport const fixtureCatalog: readonly FixtureEntry[] = [\n${entries}\n]\n`

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, output)
console.log(
  `Generated ${fixtures.length} fixture imports at ${path.relative(repositoryRoot, outputPath)}`,
)
