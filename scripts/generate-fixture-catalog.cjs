const fs = require('node:fs')
const path = require('node:path')

const repositoryRoot = path.resolve(__dirname, '..')
const sourceRoot = path.join(repositoryRoot, 'src')
const outputPath = path.join(repositoryRoot, 'example', 'fixtures', 'catalog.ts')

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name)
    if (entry.isDirectory()) return walk(entryPath)
    return entry.isFile() && entry.name.endsWith('.tsx') ? [entryPath] : []
  })
}

function readTag(source, tag) {
  const match = source.match(new RegExp(`@${tag}\\s+([^\\r\\n*]+)`))
  return match?.[1].trim() || null
}

function componentTitle(component) {
  return component
    .split('/')
    .map((part) => part.replace(/[-_]+(.)/g, (_, character) => character.toUpperCase()))
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

function toPosix(value) {
  return value.split(path.sep).join('/')
}

function stringLiteral(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function displayWidth(value) {
  return [...value].reduce(
    (width, character) =>
      width +
      (/^[\u1100-\u115f\u2329\u232a\u2e80-\u303e\u3040-\ua4cf\uac00-\ud7a3\uf900-\ufaff\ufe10-\ufe6f\uff00-\uff60\uffe0-\uffe6]$/u.test(
        character,
      )
        ? 2
        : 1),
    0,
  )
}

function propertyLine(name, value) {
  const line = `    ${name}: ${stringLiteral(value)},`
  return displayWidth(line) > 100 ? `    ${name}:\n      ${stringLiteral(value)},` : line
}

const componentDirectories = fs
  .readdirSync(sourceRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .filter((entry) => fs.existsSync(path.join(sourceRoot, entry.name, '__fixtures__')))
  .filter((entry) => walk(path.join(sourceRoot, entry.name, '__fixtures__')).length > 0)
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right))

const fixtures = componentDirectories.map((component, index) => {
  const fixtureRoot = path.join(sourceRoot, component, '__fixtures__')
  const examplesRoot = path.join(fixtureRoot, 'examples')
  const overviewPath = path.join(fixtureRoot, 'overview.tsx')
  const directFixtureFiles = fs
    .readdirSync(fixtureRoot, { withFileTypes: true })
    .filter(
      (entry) => entry.isFile() && entry.name.endsWith('.tsx') && entry.name !== 'overview.tsx',
    )
    .map((entry) => entry.name)

  if (directFixtureFiles.length > 0) {
    throw new Error(
      `[fixtures:generate] ${component} has fixture files outside __fixtures__/examples: ${directFixtureFiles.join(', ')}. Move them into examples/ and keep overview.tsx as the component entry.`,
    )
  }

  if (!fs.existsSync(examplesRoot)) {
    throw new Error(`[fixtures:generate] ${component} is missing __fixtures__/examples/.`)
  }

  if (!fs.existsSync(overviewPath)) {
    throw new Error(
      `[fixtures:generate] ${component} has examples but is missing __fixtures__/overview.tsx.`,
    )
  }

  const exampleFiles = walk(examplesRoot).sort((left, right) => left.localeCompare(right))
  if (exampleFiles.length === 0) {
    throw new Error(`[fixtures:generate] ${component} has no .tsx files in __fixtures__/examples/.`)
  }

  const overviewSource = fs.readFileSync(overviewPath, 'utf8')
  const relativeOverviewPath = toPosix(path.relative(repositoryRoot, overviewPath))
  const title = componentTitle(component)

  return {
    component,
    description: readTag(overviewSource, 'description') || `${title} component overview.`,
    id: component,
    importName: `ComponentOverview${index}`,
    importPath: `../../${relativeOverviewPath.replace(/\.tsx$/, '')}`,
    title,
  }
})

const imports = fixtures
  .map(({ importName, importPath }) => `import ${importName} from '${importPath}'`)
  .join('\n')
const entries = fixtures
  .map(({ component, description, id, importName, title }) =>
    [
      '  {',
      `    Component: ${importName},`,
      propertyLine('component', component),
      propertyLine('description', description),
      propertyLine('id', id),
      propertyLine('title', title),
      '  },',
    ].join('\n'),
  )
  .join('\n')

const output = `// This file is generated by scripts/generate-fixture-catalog.cjs.\nimport type { ComponentType } from 'react'\n\n${imports}\n\nexport interface ComponentFixtureEntry {\n  Component: ComponentType\n  component: string\n  description: string\n  id: string\n  title: string\n}\n\nexport const componentCatalog: readonly ComponentFixtureEntry[] = [\n${entries}\n]\n`

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, output)
console.log(
  `Generated ${fixtures.length} component overview imports at ${path.relative(repositoryRoot, outputPath)}`,
)
